pub(crate) mod storage_reader_leases {
    use sea_orm::entity::prelude::*;

    /// Protects a storage location from deletion while it is read.
    #[sea_orm::model]
    #[derive(Debug, Clone, PartialEq, Eq, DeriveEntityModel)]
    #[sea_orm(table_name = "storage_reader_leases", rename_all = "camelCase")]
    pub(crate) struct Model {
        #[sea_orm(primary_key, auto_increment = false)]
        pub(crate) id: String,
        pub(crate) storage_location_id: String,
        pub(crate) scope: ReaderLeaseScope,
        pub(crate) expires_at: i64,
    }

    impl ActiveModelBehavior for ActiveModel {}

    /// Which data a Storage Reader Lease protects.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, EnumIter, DeriveActiveEnum)]
    #[sea_orm(rs_type = "String", db_type = "String(StringLen::N(16))")]
    pub(crate) enum ReaderLeaseScope {
        #[sea_orm(string_value = "parts")]
        Parts,
        #[sea_orm(string_value = "storage")]
        Storage,
    }
}
